/** 取某部作品的一线人物和知名势力；没有配置时返回空名单 */
function getFamousCharacters(work) {
  return FAMOUS_CHARACTERS[work] || { characters: [], factions: [] };
}

/** 统计标题里出现了名单中的几个人物或势力 */
function countFamousNames(title, work) {
  const { characters, factions } = getFamousCharacters(work);
  const text = String(title || '');
  return [...characters, ...factions].filter(name => text.includes(name)).length;
}

