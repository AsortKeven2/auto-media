/** 获取类别定义 */
function getCategory(name) {
  return CATEGORIES[name] || null;
}

/** 获取类别对应的结构骨架，未定义时按判定型处理 */
function getCategorySkeleton(name) {
  const cat = getCategory(name);
  if (!cat) return null;
  return cat.skeleton || '判定型';
}

/**
 * 构建选题 prompt 中的类别说明
 */
function buildCategoryPromptSection(platform = null) {
  return Object.entries(CATEGORIES).filter(([, cat]) => (
    !platform || !cat.platforms || cat.platforms.includes(platform)
  )).map(([name, cat]) => {
    return `- ${name}（${cat.subtitle}）：${cat.topicStyle}`;
  }).join('\n');
}

