/** 获取类别定义 */
function getCategory(name) {
  return CATEGORIES[name] || null;
}

/**
 * 构建选题 prompt 中的类别说明
 */
function buildCategoryPromptSection() {
  return Object.entries(CATEGORIES).map(([name, cat]) => {
    return `- ${name}（${cat.subtitle}）：${cat.topicStyle}`;
  }).join('\n');
}

module.exports = { CATEGORIES, getCategory, buildCategoryPromptSection };
