/** 获取类别定义 */
function getCategory(name) {
  return CATEGORIES[name] || null;
}

/**
 * 构建选题 prompt 中的类别说明
 */
function buildCategoryPromptSection() {
  return Object.entries(CATEGORIES).filter(([name]) => name !== '热文风格').map(([name, cat]) => {
    return `- ${name}（${cat.subtitle}）：${cat.topicStyle}`;
  }).join('\n');
}

